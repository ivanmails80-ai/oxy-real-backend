/**
 * Risolve una chiave in notazione puntata (es. "otp.backToLogin") su un oggetto annidato.
 * Supporta anche chiavi numeriche (es. "settings.2fa.sms" -> settings["2fa"].sms).
 */
const getNested = (obj, path) => {
  if (!obj || typeof path !== 'string') return undefined;
  const parts = path.split('.');
  let current = obj;
  for (const part of parts) {
    if (current == null) return undefined;
    current = current[part];
  }
  return typeof current === 'string' ? current : undefined;
};

/**
 * Sostituisce {{param}} e {param} nel testo con i valori da params.
 */
const interpolate = (str, params) => {
  if (!str || typeof str !== 'string' || !params || typeof params !== 'object') return str;
  return str
    .replace(/\{\{(\w+)\}\}/g, (_, key) => (params[key] !== undefined ? params[key] : `{{${key}}}`))
    .replace(/\{(\w+)\}/g, (_, key) => (params[key] !== undefined ? params[key] : `{${key}}`));
};

