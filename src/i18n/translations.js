export const getLanguage = () => currentLanguage;

/**
 * Restituisce la traduzione per la chiave in notazione puntata (es. "otp.backToLogin").
 * @param {string} lang - Codice lingua ('it', 'en', 'fr', 'es', 'ar')
 * @param {string} key - Chiave in notazione puntata (es. "otp.backToLogin")
 * @param {object} params - Oggetto per interpolazione (es. { seconds: 60 } -> {{seconds}} nel testo)
 * @returns {string} Traduzione interpolata o chiave se non trovata
 */
export const t = (lang, key, params = {}) => {
  // Valida e normalizza la lingua
  const validLang = LANGUAGES.includes(lang) ? lang : 'it';
  const langObj = translations[validLang] || translations.it;
  
  // Cerca la traduzione nella lingua richiesta
  let translation = getNested(langObj, key);
  
  // Fallback all'italiano se non trovata
  if (translation == null) {
    translation = getNested(translations.it, key);
  }
  
  // Se ancora non trovata, restituisci la chiave
  if (translation == null || typeof translation !== 'string') {
    return key;
  }
  
  // Interpola i parametri
  return interpolate(translation, params);
};
